// Phone number formatting utilities
export const formatPhoneNumber = (value) => {
  // Remove all non-numeric characters
  const cleanedValue = value.replace(/\D/g, '')
  
  // Format as (XXX) XXX-XXXX for US/CA numbers
  if (cleanedValue.length <= 10) {
    if (cleanedValue.length >= 6) {
      return `(${cleanedValue.slice(0, 3)}) ${cleanedValue.slice(3, 6)}-${cleanedValue.slice(6)}`
    } else if (cleanedValue.length >= 3) {
      return `(${cleanedValue.slice(0, 3)}) ${cleanedValue.slice(3)}`
    } else {
      return cleanedValue
    }
  }
  
  // For international numbers, just return with spaces
  return cleanedValue.replace(/(\d{1,3})(\d{1,3})(\d{1,4})(\d{0,4})/, '$1 $2 $3 $4').trim()
}

// ZIP/Postal code validation
export const validatePostalCode = (postalCode, countryCode) => {
  const patterns = {
    'US': /^\d{5}(-\d{4})?$/, // 12345 or 12345-6789
    'CA': /^[A-Za-z]\d[A-Za-z][ -]?\d[A-Za-z]\d$/, // A1A 1A1 or A1A-1A1
    'GB': /^[A-Z]{1,2}\d[A-Z\d]?\s?\d[A-Z]{2}$/i, // UK postcodes
    'DE': /^\d{5}$/, // German postcodes
    'FR': /^\d{5}$/, // French postcodes
    'AU': /^\d{4}$/, // Australian postcodes
    'JP': /^\d{3}-?\d{4}$/, // Japanese postcodes
    'MX': /^\d{5}$/ // Mexican postcodes
  }
  
  const pattern = patterns[countryCode]
  if (!pattern) return true // Allow any format for unlisted countries
  
  return pattern.test(postalCode)
}

